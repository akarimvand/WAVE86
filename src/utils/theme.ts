export function applyThemeToDocument(paletteKey: ThemePaletteKey) {
  const pal = THEME_PALETTES[paletteKey] || THEME_PALETTES.wave;
  const root = document.documentElement;

  root.style.setProperty('--color-primary', pal.primaryHex);
  root.style.setProperty('--color-primary-hover', pal.primaryHoverHex);
  root.style.setProperty('--color-primary-light', pal.primaryLightHex);
  root.style.setProperty('--color-primary-border', pal.borderHex);
  root.style.setProperty('--color-primary-text', pal.textHex);

  // Set all shade variables for dynamic Tailwind mapping
  root.style.setProperty('--color-primary-50', pal.shades[50]);
  root.style.setProperty('--color-primary-100', pal.shades[100]);
  root.style.setProperty('--color-primary-200', pal.shades[200]);
  root.style.setProperty('--color-primary-300', pal.shades[300]);
  root.style.setProperty('--color-primary-400', pal.shades[400]);
  root.style.setProperty('--color-primary-500', pal.shades[500]);
  root.style.setProperty('--color-primary-600', pal.shades[600]);
  root.style.setProperty('--color-primary-700', pal.shades[700]);
  root.style.setProperty('--color-primary-800', pal.shades[800]);
  root.style.setProperty('--color-primary-900', pal.shades[900]);

  root.setAttribute('data-theme', paletteKey);
}

